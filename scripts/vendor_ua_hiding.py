"""Regenerate src/evidence_judge/ingest/ua_hiding.css from the specifications browsers follow.

The page-text reader must know which elements a browser never renders. Rather than a hand list,
it reads the user-agent rules that hide elements, vendored from:

- the WHATWG HTML Standard, "Rendering" (its user-agent stylesheet blocks), CC BY 4.0;
- MathML Core, "User Agent Stylesheet", W3C Software and Document License;
- SVG 2, "never-rendered element", W3C Software and Document License.

Only rules that hide (``display: none``, ``content-visibility: hidden``, ``visibility:
hidden``) are kept, each section under the ``@namespace`` it applies to, followed by the
judge's own adjustments (`LOCAL`). Attribution is in ua_hiding.NOTICE next to the file.

    uv run python scripts/vendor_ua_hiding.py          # rewrite the file
    uv run python scripts/vendor_ua_hiding.py --check  # exit 1 if upstream changed
"""

from __future__ import annotations

import argparse
import html
import re
import sys
import urllib.request
from pathlib import Path

HTML_URL = "https://html.spec.whatwg.org/multipage/rendering.html"
MATHML_URL = "https://w3c.github.io/mathml-core/"
SVG_URL = "https://svgwg.org/svg2-draft/render.html"
OUT = Path(__file__).resolve().parents[1] / "src/evidence_judge/ingest/ua_hiding.css"

HTML_NS = "http://www.w3.org/1999/xhtml"
SVG_NS = "http://www.w3.org/2000/svg"
MATHML_NS = "http://www.w3.org/1998/Math/MathML"

_PRE = re.compile(r"<pre[^>]*>(.*?)</pre>", re.DOTALL)
_TAG = re.compile(r"<[^>]+>")
_HIDES = re.compile(
    r"\b(?:display\s*:\s*none|content-visibility\s*:\s*hidden|visibility\s*:\s*hidden)\b"
)
_NAMESPACE = re.compile(r"@namespace[^;]*;\s*")
_NEVER_RENDERED = re.compile(
    r'id="TermNeverRenderedElement".*?<dd>(.*?)</dd>', re.DOTALL | re.IGNORECASE
)
_ELEMENT_NAME = re.compile(r"<span>([A-Za-z]+)</span></a>")

HEADER = """\
/* The rules by which a browser's own styles hide elements, read by the page-text reader
   (evidence_judge.ingest.css) as user-agent-origin rules beneath every page's styles.

   Generated by scripts/vendor_ua_hiding.py; do not edit by hand. Sources and licences are in
   ua_hiding.NOTICE:
   - WHATWG HTML Standard, Rendering: {html}
   - MathML Core, User Agent Stylesheet: {mathml}
   - SVG 2, never-rendered element: {svg}
*/
"""

LOCAL: dict[str, str] = {
    HTML_NS: """\
/* evidence-judge: hidden=until-found content is revealed by find-in-page and fragment links
   without a script, so its visibility is unknown rather than hidden. */
[hidden=until-found i]:not(embed) {
  content-visibility: var(--evidence-judge-unknown);
}
""",
    SVG_NS: """\
/* evidence-judge: Filter Effects: a filter's primitives are never rendered as content. */
filter {
  display: none;
}
""",
    MATHML_NS: """\
/* evidence-judge: an annotation outside <semantics> may or may not render. */
annotation, annotation-xml {
  display: var(--evidence-judge-unknown);
}
""",
}


def fetch(url: str) -> str:
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read().decode("utf-8")


def _css_blocks(page: str, namespace: str) -> list[str]:
    """The text of each ``<pre>`` stylesheet block of `page` declaring `namespace`."""
    blocks = [html.unescape(_TAG.sub("", b)) for b in _PRE.findall(page)]
    return [b for b in blocks if b.lstrip().startswith("@namespace") and namespace in b]


def _rules(css: str) -> list[tuple[str, str]]:
    """Top-level (prelude, body) pairs of `css`, comments dropped."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.DOTALL)
    css = _NAMESPACE.sub("", css)
    out: list[tuple[str, str]] = []
    at, depth, start = 0, 0, 0
    prelude = ""
    while at < len(css):
        char = css[at]
        if char == "{":
            if depth == 0:
                prelude, start = css[:at].rsplit("}", 1)[-1].strip(), at + 1
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                out.append((prelude, css[start:at]))
        at += 1
    return out


def _hiding(css: str) -> list[str]:
    """The rules of `css` that hide an element (not a pseudo-element), as written."""
    kept: list[str] = []
    for prelude, body in _rules(css):
        if prelude.startswith("@"):
            inner = _hiding(body)
            if inner:
                kept.append(f"{prelude} {{\n" + "".join(f"  {r}" for r in inner) + "}\n")
            continue
        if "::" in prelude or not _HIDES.search(body):
            continue
        lines = [line.strip() for line in body.strip().splitlines() if line.strip()]
        kept.append(f"{' '.join(prelude.split())} {{ {' '.join(lines)} }}\n")
    return kept


def _never_rendered(page: str) -> list[str]:
    found = _NEVER_RENDERED.search(page)
    if found is None:
        raise SystemExit("SVG 2: the never-rendered element definition was not found")
    return sorted(set(_ELEMENT_NAME.findall(found.group(1))), key=str.lower)


def generate(html_page: str, mathml_page: str, svg_page: str) -> str:
    sections = [HEADER.format(html=HTML_URL, mathml=MATHML_URL, svg=SVG_URL)]
    html_rules = [r for b in _css_blocks(html_page, HTML_NS) for r in _hiding(b)]
    mathml_rules = [r for b in _css_blocks(mathml_page, MATHML_NS) for r in _hiding(b)]
    names = _never_rendered(svg_page)
    if not html_rules or not mathml_rules or not names:
        raise SystemExit("a source no longer has the expected rules; check the extractors")
    svg_rules = [f"{', '.join(names)} {{ display: none; }}\n"]
    for namespace, rules in (
        (HTML_NS, html_rules),
        (SVG_NS, svg_rules),
        (MATHML_NS, list(dict.fromkeys(mathml_rules))),
    ):
        sections.append(f'\n@namespace "{namespace}";\n\n' + "".join(rules) + "\n")
        sections.append(LOCAL[namespace])
    return "".join(sections)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Regenerate ua_hiding.css from the HTML, SVG and MathML specifications."
    )
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args()
    text = generate(fetch(HTML_URL), fetch(MATHML_URL), fetch(SVG_URL))
    if args.check:
        if OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of date: run scripts/vendor_ua_hiding.py", file=sys.stderr)
            return 1
        print(f"{OUT} is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
